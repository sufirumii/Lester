/**
 * Build the deliverable: lester-v1.0.4.zip (+ SHA256SUMS inside, zip hash outside).
 * Run: bun run package
 *
 * The package is the whole project (source, migrations, brand, marketing site,
 * docs, Docker, scripts, tests) minus: node_modules, .next, local databases,
 * logs, .env, keys, and any builder-environment artifacts.
 *
 * v1.0.4 — the package contains no dotfiles and no bracket-named paths, so
 * every file survives a GitHub web drag-and-drop upload (GitHub's web
 * uploader skips OS-hidden dotfiles and rejects `[`/`]` in paths, failing
 * with "Something went really wrong, and we can't process that file" and
 * silently dropping every file queued after it). .gitignore/.dockerignore
 * are recreated locally by install.sh / install.ps1 when missing.
 */
import AdmZip from "adm-zip";
import { createHash } from "node:crypto";
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";

const ROOT = path.join(import.meta.dir, "..");
const NAME = "lester-v1.0.4";
const STAGE = path.join(ROOT, "staging", NAME);
const OUT = path.join(ROOT, "dist", `${NAME}.zip`);

const EXCLUDE_DIRS = new Set([
  "node_modules", ".next", ".git", ".github", "staging", "agent-ctx", "dist",
  "db", // runtime data — the app creates this directory on first boot
  // builder-environment scaffolds (not part of the product):
  ".zscripts", "skills", "mini-services", "examples", "download", "upload",
  "test-output", "playwright-report", "test-results",
]);
const EXCLUDE_FILES = new Set([
  // dotfiles are skipped by GitHub web uploads (OS-hidden) — the package ships
  // none; install.sh / install.ps1 recreate .gitignore/.dockerignore locally:
  ".gitignore", ".dockerignore",
  "dev.log", "server.log", ".env", ".DS_Store", "bun.lockb",
  `${NAME}.zip`, "SHA256SUMS", "Caddyfile", "lester-keys-bundle.txt",
  "tsconfig.tsbuildinfo", "next-env.d.ts", // regenerated by next build/dev
]);
const EXCLUDE_EXT = new Set([".zip", ".tar.gz", ".pem", ".key"]);

function copyTree(src: string, dest: string, rel: string) {
  mkdirSync(dest, { recursive: true });
  for (const entry of readdirSync(src, { withFileTypes: true })) {
    const relPath = rel ? `${rel}/${entry.name}` : entry.name;
    if (entry.isDirectory()) {
      if (EXCLUDE_DIRS.has(entry.name)) continue;
      copyTree(path.join(src, entry.name), path.join(dest, entry.name), relPath);
    } else {
      if (EXCLUDE_FILES.has(entry.name)) continue;
      if (EXCLUDE_EXT.has(path.extname(entry.name))) continue;
      if (entry.name.endsWith(".tar.gz")) continue;
      cpSync(path.join(src, entry.name), path.join(dest, entry.name));
    }
  }
}

function sha256File(p: string): string {
  return createHash("sha256").update(readFileSync(p)).digest("hex");
}

function listFiles(dir: string, base = dir): string[] {
  const out: string[] = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...listFiles(full, base));
    else out.push(path.relative(base, full));
  }
  return out;
}

function fmtSize(bytes: number): string {
  if (bytes > 1024 * 1024) return `${(bytes / 1024 / 1024).toFixed(2)} MB`;
  return `${(bytes / 1024).toFixed(1)} KB`;
}

// ── 1. Stage ─────────────────────────────────────────────────────────────────

rmSync(path.join(ROOT, "staging"), { recursive: true, force: true });
mkdirSync(STAGE, { recursive: true });
copyTree(ROOT, STAGE, "");

// ── 2. SHA256SUMS for every payload file ────────────────────────────────────

const files = listFiles(STAGE).sort();
const sums = files.map((f) => `${sha256File(path.join(STAGE, f))}  ${f}`).join("\n");
writeFileSync(path.join(STAGE, "SHA256SUMS"), `${sums}\n`);

// ── 3. Zip (wrapped in a top-level lester-v1.0.4/ folder) ───────────────────

const zip = new AdmZip();
zip.addLocalFolder(STAGE, NAME);
mkdirSync(path.join(ROOT, "dist"), { recursive: true });
zip.writeZip(OUT);
const zipBytes = statSync(OUT).size;
const zipHash = sha256File(OUT);
writeFileSync(path.join(ROOT, "dist", "SHA256SUMS"), `${zipHash}  ${NAME}.zip\n`);

// ── 4. Report ────────────────────────────────────────────────────────────────

const bracketFree = files.every((f) => !/[\[\]]/.test(f));
const dotFree = files.every((f) => !f.split("/").some((p) => p.startsWith(".")));
console.log(`✔ ${NAME}.zip built → dist/${NAME}.zip`);
console.log(`  size    : ${fmtSize(zipBytes)}`);
console.log(`  files   : ${files.length + 1} (incl. SHA256SUMS)`);
console.log(`  sha256  : ${zipHash}`);
console.log(`  github web-upload safe: no bracket paths: ${bracketFree}, no dotfiles: ${dotFree}`);
console.log(`  location: ${OUT}`);
rmSync(path.join(ROOT, "staging"), { recursive: true, force: true });
